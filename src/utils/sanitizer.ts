/**
 * Oops La Book Store — Input & HTML Sanitizer
 * Prevents XSS attacks by escaping dangerous HTML characters.
 */

export function escapeHtml(str: string | undefined | null): string {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
